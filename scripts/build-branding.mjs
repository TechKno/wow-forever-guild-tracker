import {readFile,readdir,mkdir,writeFile} from 'node:fs/promises';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {validateConfig} from '../src/config.mjs';

const project=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const escapeHTML=value=>String(value).replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const safeJSON=value=>JSON.stringify(value).replace(/[<>&\u2028\u2029]/g,char=>'\\u'+char.charCodeAt(0).toString(16).padStart(4,'0'));
function contrastColor(hex){
  const rgb=hex.slice(1).match(/../g).map(value=>parseInt(value,16)/255).map(value=>value<=.04045?value/12.92:((value+.055)/1.055)**2.4);
  return .2126*rgb[0]+.7152*rgb[1]+.0722*rgb[2]>.179?'#1d180f':'#fffaf0';
}
export async function buildBranding(raw,{outputDir=join(project,'public'),templateDir=join(project,'branding/templates')}={}){
  const config=validateConfig(raw),{guild,site,discord}=config;
  const brand={guildName:guild.name,siteTitle:site.title,region:guild.region.toUpperCase(),ruleset:guild.ruleset.name,
    regionRuleset:guild.region.toUpperCase()+' '+guild.ruleset.name,botName:discord.botName,origin:site.origin};
  const publicIdentity={guildName:brand.guildName,region:brand.region,ruleset:brand.ruleset};
  const logo=site.logo.toLowerCase(),logoType=logo.endsWith('.svg')?'image/svg+xml':logo.endsWith('.webp')?'image/webp':logo.endsWith('.jpg')||logo.endsWith('.jpeg')?'image/jpeg':'image/png';
  const values={GUILD_NAME:guild.name,GUILD_NAME_UPPER:guild.name.toUpperCase(),SITE_TITLE:site.title,SITE_TITLE_UPPER:site.title.toUpperCase(),
    TAGLINE:site.tagline,DESCRIPTION:site.description,MOTTO:site.motto,MOTTO_UPPER:site.motto.toUpperCase(),BOT_NAME:discord.botName,
    REGION:brand.region,RULESET:brand.ruleset,REGION_RULESET:brand.regionRuleset,REGION_RULESET_UPPER:brand.regionRuleset.toUpperCase(),
    SITE_ORIGIN:site.origin,LOGO:site.logo,HERO:site.hero,HERO_URL:site.origin+site.hero,LOGO_TYPE:logoType,LANGUAGE:guild.locale.replace('_','-')};
  const codeValues={PUBLIC_BRAND_JSON:safeJSON(brand),PUBLIC_IDENTITY_JSON:safeJSON(publicIdentity),BOT_NAME_JSON:safeJSON(discord.botName)};
  await mkdir(outputDir,{recursive:true});
  const generated=[];
  for(const name of (await readdir(templateDir)).filter(name=>name.endsWith('.tpl')).sort()){
    const template=await readFile(join(templateDir,name),'utf8');
    const rendered=template.replace(/\{\{([A-Z_]+)\}\}/g,(_match,key)=>{
      if(Object.hasOwn(codeValues,key))return codeValues[key];
      if(!Object.hasOwn(values,key))throw Error('Unknown branding template token: '+key);
      return escapeHTML(values[key]);
    });
    const filename=name.slice(0,-4);await writeFile(join(outputDir,filename),rendered);generated.push(filename);
  }
  // Colors are validated six-digit hex values. No raw text, URLs or secret
  // environment values are interpolated into stylesheet declarations.
  const accent=site.theme.accent,background=site.theme.background,contrast=contrastColor(accent);
  const css=`/* Generated by scripts/build-branding.mjs from public branding settings. */\n:root{--brand-accent:${accent};--brand-background:${background};--brand-on-accent:${contrast};--gold:var(--brand-accent);--bg:var(--brand-background);--paper:var(--brand-background)}\nbody{background-color:var(--brand-background)}.privacy-page{background:var(--brand-background)}.button.primary,.button-primary,.hall-form .button.primary{background:var(--brand-accent);border-color:var(--brand-accent);color:var(--brand-on-accent)}.button.primary:hover,.button-primary:hover,.hall-form .button.primary:hover{filter:brightness(.92)}a:focus-visible,button:focus-visible,input:focus-visible,select:focus-visible,textarea:focus-visible{outline-color:var(--brand-accent)}.composition-row progress{accent-color:var(--brand-accent)}.composition-row progress::-webkit-progress-value{background:var(--brand-accent)}\n`;
  await writeFile(join(outputDir,'brand.css'),css);generated.push('brand.css');
  return {generated,config};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const args=process.argv.slice(2);let configPath=join(project,'guild.config.json'),outputDir=join(project,'public');
  for(let index=0;index<args.length;index++){
    if(args[index]==='--config'&&args[index+1])configPath=resolve(args[++index]);
    else if(args[index]==='--out-dir'&&args[index+1])outputDir=resolve(args[++index]);
    else throw Error('Usage: node scripts/build-branding.mjs [--config PATH] [--out-dir DIRECTORY]');
  }
  let raw;try{raw=JSON.parse(await readFile(configPath,'utf8'));}catch{throw Error('Could not read valid guild configuration JSON; check the file path and syntax');}
  const result=await buildBranding(raw,{outputDir});
  console.log('Built '+result.generated.length+' public branding files.');
}
